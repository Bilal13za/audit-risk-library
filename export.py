"""
Workpaper export for the Audit Risk and Evidence Library.

export_csv(plan, path)  - one denormalised CSV (risk x procedure rows)
export_excel(plan, path) - formatted multi-sheet workbook (openpyxl)

Both are pure functions of the assessment plan returned by
engine.RuleEngine.assess(), so exports are deterministic and testable.
"""

import csv
from datetime import date

CSV_COLUMNS = [
    "Risk ID", "Risk title", "Why the risk exists", "Potential misstatement",
    "Affected assertions", "Relevant control(s)", "Procedure ID", "Procedure title",
    "Procedure type", "Test type", "Procedure steps", "Assertions tested",
    "Required evidence", "Expected result", "Exception criteria",
    "Follow-up actions", "Sources", "Triggered by rule(s)",
]


def _risk_rows(plan):
    rows = []
    for risk in plan["risks"]:
        assertions = "; ".join(f"{a['id']} {a['name']}: {a['why_relevant']}" for a in risk["assertions"])
        controls = "; ".join(c["description"] for c in risk["controls"])
        for proc in risk["procedures"]:
            evidence = "; ".join(e["name"] for e in proc["evidence"])
            rows.append({
                "Risk ID": risk["id"],
                "Risk title": risk["title"],
                "Why the risk exists": risk["causes"] or "",
                "Potential misstatement": risk["potential_consequences"] or "",
                "Affected assertions": assertions,
                "Relevant control(s)": controls,
                "Procedure ID": proc["id"],
                "Procedure title": proc["title"],
                "Procedure type": proc["procedure_type"],
                "Test type": proc["test_type"],
                "Procedure steps": proc["steps"] or "",
                "Assertions tested": ", ".join(proc["assertions"]),
                "Required evidence": evidence,
                "Expected result": proc["expected_result"] or "",
                "Exception criteria": proc["exception_criteria"] or "",
                "Follow-up actions": proc["follow_up"] or "",
                "Sources": "; ".join(filter(None, [risk["source_reference"], proc["source_reference"]])),
                "Triggered by rule(s)": ", ".join(proc["triggered_by_rules"]),
            })
    return rows


def export_csv(plan, path):
    rows = _risk_rows(plan)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    return len(rows)


def export_excel(plan, path):
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    header_font = Font(bold=True, color="FFFFFF", size=11)
    header_fill = PatternFill("solid", fgColor="1F4E5F")
    title_font = Font(bold=True, size=14, color="1F4E5F")
    wrap = Alignment(wrap_text=True, vertical="top")
    thin = Side(style="thin", color="B0B0B0")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    def style_sheet(ws, widths):
        for col, w in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(col)].width = w
        for row in ws.iter_rows():
            for cell in row:
                cell.alignment = wrap
                cell.border = border

    def add_header(ws, headers):
        ws.append(headers)
        for cell in ws[1]:
            cell.font = header_font
            cell.fill = header_fill

    # ---- Cover -----------------------------------------------------------
    ws = wb.active
    ws.title = "Cover"
    ws["A1"] = "Audit Risk and Testing Plan"
    ws["A1"].font = title_font
    ws["A2"] = "Generated by the Audit Risk and Evidence Library (deterministic, offline)"
    ws["A3"] = f"Date: {date.today().isoformat()}"
    ws["A4"] = f"Business factors selected: {', '.join(plan['selected_factor_ids']) or 'none'}"
    ws["A5"] = f"Rules triggered: {plan['counts']['rules_triggered']} | Risks: {plan['counts']['risks']} | " \
               f"Procedures: {plan['counts']['procedures']} | Controls: {plan['counts']['controls']}"
    ws["A7"] = "Professional judgment notice"
    ws["A7"].font = Font(bold=True)
    ws["A8"] = ("This plan lists POSSIBLE risks and SUGGESTED procedures. A risk factor does not prove a "
                "misstatement exists. A failed control test does not prove the financial statements are "
                "misstated, and a passed control test does not prove the balance is correct. "
                "Apply professional judgment throughout.")
    ws["A8"].alignment = wrap
    ws.column_dimensions["A"].width = 110
    ws.row_dimensions[8].height = 60

    # ---- Risk register ----------------------------------------------------
    ws = wb.create_sheet("Risk register")
    add_header(ws, ["Risk ID", "Risk title", "Why the risk exists", "Potential misstatement",
                    "Assertions", "Triggered by rule(s)", "Source"])
    for r in plan["risks"]:
        ws.append([
            r["id"], r["title"], r["causes"], r["potential_consequences"],
            "; ".join(f"{a['id']} ({a['name']})" for a in r["assertions"]),
            ", ".join(r["triggered_by_rules"]), r["source_reference"],
        ])
    style_sheet(ws, [12, 34, 50, 50, 40, 20, 30])

    # ---- Procedures --------------------------------------------------------
    ws = wb.create_sheet("Audit procedures")
    add_header(ws, ["Risk ID", "Proc. ID", "Procedure", "Type", "Test type",
                    "Steps", "Expected result", "Exception criteria", "Follow-up"])
    for r in plan["risks"]:
        for p in r["procedures"]:
            ws.append([r["id"], p["id"], p["title"], p["procedure_type"], p["test_type"],
                       p["steps"], p["expected_result"], p["exception_criteria"], p["follow_up"]])
    style_sheet(ws, [10, 10, 30, 18, 16, 60, 40, 40, 40])

    # ---- Evidence ----------------------------------------------------------
    ws = wb.create_sheet("Evidence")
    add_header(ws, ["Procedure ID", "Evidence", "Source", "Reliability considerations",
                    "Limitations", "Expected characteristics"])
    for r in plan["risks"]:
        for p in r["procedures"]:
            for e in p["evidence"]:
                ws.append([p["id"], e["name"], e["source"], e["reliability_notes"],
                           e["limitations"], e["expected_characteristics"]])
    style_sheet(ws, [12, 34, 14, 50, 40, 40])

    # ---- Rules -------------------------------------------------------------
    ws = wb.create_sheet("Rules applied")
    add_header(ws, ["Rule ID", "Rule name", "Version", "Priority", "Effective date",
                    "Rationale", "Missing information", "Review status"])
    for t in plan["triggered_rules"]:
        ws.append([t["rule_id"], t["rule_name"], t["version"], t["priority"], t["effective_date"],
                   t["rationale"], "\n".join(f"- {m}" for m in t["missing_information"]),
                   t["review_status"]])
    style_sheet(ws, [14, 40, 10, 10, 14, 50, 50, 14])

    wb.save(path)
    return path
